// Generated by @tanstack/router-plugin on first `dev` or `build`.
import { routeTree } from './routeTree.gen'

// An ended session or temporary sign-in details answer every request the same way, so one place handles them for
// every page and action: before, each page showed "You don't have access" with a blank role (QA 17 November).
let leaving = false
function onRequestError(error: unknown) {
  const where = authRedirectFor(error)
  const here = window.location.pathname + window.location.search
  if (!where || leaving || signedOutPaths.some((path) => window.location.pathname.startsWith(path))) return
  leaving = true
  if (where === 'sign-in') queryClient.removeQueries()
  else void queryClient.invalidateQueries({ queryKey: ['session'] })
  void router.navigate({ href: where === 'sign-in' ? sessionEndedHref(here) : '/first-login?redirect=' + encodeURIComponent(here), replace: true }).finally(() => { leaving = false })
}
const queryClient: QueryClient = new QueryClient({
  queryCache: new QueryCache({ onError: onRequestError }),
  mutationCache: new MutationCache({ onError: onRequestError }),
})
const router = createRouter({
  routeTree,
  context: { queryClient },
  defaultViewTransition: true,
  defaultPreload: "intent",
  // Router-wide fallbacks. A route with its own `errorComponent` (the session check, for
  // example) still takes over for its own errors; this only catches everything else.
  defaultNotFoundComponent: RouteNotFound,
  defaultErrorComponent: RouteError,
})

declare module '@tanstack/react-router' {
  interface Register {
    router: typeof router
  }
}

// Remember the theme on this device, so the next load starts in it (public/theme-boot.js applies it before drawing).
function rememberTheme() {
  try {
    const theme = document.documentElement.getAttribute('data-theme')
    if (theme) localStorage.setItem('accs.theme', theme)
    else localStorage.removeItem('accs.theme')
  } catch {
    // Storage can be blocked (private windows); the theme still applies for this visit.
  }
}
new MutationObserver(rememberTheme).observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] })

void initObservability()
initAnalytics(router)

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <QueryClientProvider client={queryClient}>
      <RouterProvider router={router} />
    </QueryClientProvider>
  </StrictMode>,
)
